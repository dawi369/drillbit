  private func dismissSystemAlerts() {
    let springboard = XCUIApplication(bundleIdentifier: "com.apple.springboard")
    for title in ["Not Now", "Don’t Allow", "Don't Allow", "Allow", "OK"] {
      let button = springboard.alerts.buttons[title]
      if button.waitForExistence(timeout: 1) { button.tap() }
    }
  }

  private func launch(_ args: [String]) -> XCUIApplication {
    let app = XCUIApplication()
    app.launchArguments = args
    app.launch()
    dismissSystemAlerts()
    return app
  }

  private func shot(_ name: String, _ app: XCUIApplication) {
    let attachment = XCTAttachment(screenshot: app.screenshot())
    attachment.name = name
    attachment.lifetime = .keepAlways
    add(attachment)
  }

  private func editor(_ app: XCUIApplication) -> XCUIElement {
    app.descendants(matching: .any).matching(identifier: "answerEditor").firstMatch
  }

